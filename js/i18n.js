window.Lang = {
  current: localStorage.getItem("al_lang") || "no",
  t(key) { return (I18N[this.current] && I18N[this.current][key]) || key; },
  set(lang) {
    this.current = lang;
    localStorage.setItem("al_lang", lang);
    this.apply();
  },
  apply() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = this.t(el.getAttribute("data-i18n-placeholder"));
    });
  },
};

window.Theme = {
  current: localStorage.getItem("al_theme") || "dark",
  apply() { document.documentElement.setAttribute("data-theme", this.current); },
  toggle() {
    this.current = this.current === "dark" ? "light" : "dark";
    localStorage.setItem("al_theme", this.current);
    this.apply();
  },
};
Theme.apply();
